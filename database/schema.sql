CREATE DATABASE IF NOT EXISTS QLHocPhan
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE QLHocPhan;

CREATE TABLE IF NOT EXISTS GiangVien (
    IDGV BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    Fullname VARCHAR(150) NOT NULL,
    Image LONGTEXT NULL,
    SumClass INT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_giangvien_fullname (Fullname),
    CONSTRAINT chk_giangvien_sumclass CHECK (SumClass >= 0)
);
